# Albanian language lives in its own auto-generated module. Merge it into
# the main translation table so t()/t_lang() resolve all three languages from one table.
from config.lang_sq import UI as _SQ_UI   # noqa: E402
TRANSLATIONS["sq"] = _SQ_UI


# Localised month names (1-indexed via month_name) so dates can be rendered with
# the month spelled out — "23 June 2026" / "23 Haziran 2026" — instead of a bare
# number, in Turkish, English, and Albanian.
MONTHS = {
    "tr": ["Ocak", "Şubat", "Mart", "Nisan", "Mayıs", "Haziran",
           "Temmuz", "Ağustos", "Eylül", "Ekim", "Kasım", "Aralık"],
    "en": ["January", "February", "March", "April", "May", "June",
           "July", "August", "September", "October", "November", "December"],
    "sq": ["Janar", "Shkurt", "Mars", "Prill", "Maj", "Qershor",
           "Korrik", "Gusht", "Shtator", "Tetor", "Nëntor", "Dhjetor"],
}


def month_name(n: int, lang: str = None) -> str:
    """Return the localised name of month `n` (1-12) in `lang` (defaults to the
    session language, English as the ultimate fallback). Out-of-range or
    non-numeric input -> ''."""
    try:
        m = int(n)
    except (TypeError, ValueError):
        return ""
    if not (1 <= m <= 12):
        return ""
    if not lang:
        import streamlit as st
        lang = st.session_state.get("lang", DEFAULT_LANG)
    return MONTHS.get(lang, MONTHS["en"])[m - 1]


def init_lang():
    import streamlit as st
    if "lang" not in st.session_state:
        st.session_state.lang = DEFAULT_LANG


def t(key: str) -> str:
    import streamlit as st
    lang = st.session_state.get("lang", DEFAULT_LANG)
    return TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))


def t_lang(key: str, lang: str) -> str:
    """Translate into an explicit language (used by the invoice, whose language is
    chosen at registration and is independent of the UI language)."""
    return TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))


def set_lang(lang: str):
    import streamlit as st
    st.session_state.lang = lang
